#include "libft.h"

unsigned int	ft_lstsize(t_list *lst)
{
	int	i;
	
	if (!lst)
	return (0);
	i = 1;
	while (lst->next != 0)
	{
		lst = lst->next;
		i++;
	}
	return (i);
}
