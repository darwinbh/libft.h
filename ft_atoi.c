#include "libft.h"

int	ft_atoi(const char *nptr)
{
	int n;
	int i;
	int r;

	i = 0;
	while (nptr[i] == ' '  || (nptr[i] >= 9 && nptr[i] <= 13))
		i++;
	n = 1;
	if (nptr[i] == '-' || nptr[i] == '+')
	{
		if (nptr[i] == '-')
			n = -n;
		i++;
	}
	r = 0;
	while (nptr[i] >= '0' && nptr[i] <= '9')
	{
		r = r * 10 + nptr[i] - '0';
		i++;
	}
	return (r * n);
}
